import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  APP_ROOT,
  E2E_FAMILY_NAME,
  TEST_EMAILS,
  assertLocalSupabaseUrl,
  loadLocalFiles,
  passwordFor,
  runLocalSql,
  scenarioForTest,
  supabaseStatusEnv,
} from './e2e-lib.mjs';

const SCRIPT = 'e2e-setup';

function parseSetupArgs(argv) {
  let scenario = 'admin';
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--scenario') {
      scenario = argv[i + 1] ?? scenario;
      i += 1;
    } else if (argv[i] === '--test') {
      scenario = scenarioForTest(Number(argv[i + 1]));
      i += 1;
    }
  }
  if (!['admin', 'admin-elder', 'admin-elders', 'admin-elder-extended'].includes(scenario)) {
    console.error(
      `${SCRIPT}: unknown scenario "${scenario}". Use admin, admin-elder, admin-elders, or admin-elder-extended.`,
    );
    process.exit(1);
  }
  return scenario;
}

const scenario = parseSetupArgs(process.argv.slice(2));

function sql(dbUrl, statement) {
  runLocalSql(dbUrl, statement);
}

async function adminJson(url, serviceKey, method, path, body) {
  const response = await fetch(`${url.replace(/\/$/, '')}${path}`, {
    method,
    headers: {
      apikey: serviceKey,
      Authorization: `Bearer ${serviceKey}`,
      'Content-Type': 'application/json',
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await response.text();
  if (!response.ok) {
    throw new Error(`Auth admin ${method} ${path} failed (${response.status})`);
  }
  return text ? JSON.parse(text) : null;
}

const { e2eEnv, secrets } = loadLocalFiles();
const localSecrets = { ...secrets };
let status;
try {
  status = supabaseStatusEnv();
} catch {
  console.error(
    `${SCRIPT} refused to run: local Supabase is not up. From patria-app run: npx supabase start`,
  );
  process.exit(1);
}

const url = e2eEnv.EXPO_PUBLIC_SUPABASE_URL || status.API_URL || '';
assertLocalSupabaseUrl(url, SCRIPT);

const serviceKey = localSecrets.SUPABASE_SERVICE_ROLE_KEY || status.SERVICE_ROLE_KEY || '';
if (!serviceKey) {
  console.error(
    `${SCRIPT}: missing local service role key. Put SUPABASE_SERVICE_ROLE_KEY in gitignored .e2e-secrets, or rely on npx supabase status. It is never written to the app env.`,
  );
  process.exit(1);
}

const dbUrl = status.DB_URL;
if (!dbUrl) {
  console.error(`${SCRIPT}: could not read local DB URL from supabase status.`);
  process.exit(1);
}

let wroteSecrets = false;
for (const n of [1, 2, 3]) {
  if (!passwordFor(localSecrets, n)) {
    localSecrets[`E2E_PASSWORD_TEST${n}`] = randomBytes(18).toString('base64url');
    wroteSecrets = true;
  }
}
if (wroteSecrets) {
  writeFileSync(
    join(APP_ROOT, '.e2e-secrets'),
    [
      '# Generated for local Docker e2e only. Never commit. Never put these in the app env.',
      `E2E_PASSWORD_TEST1=${localSecrets.E2E_PASSWORD_TEST1}`,
      `E2E_PASSWORD_TEST2=${localSecrets.E2E_PASSWORD_TEST2}`,
      `E2E_PASSWORD_TEST3=${localSecrets.E2E_PASSWORD_TEST3}`,
      '',
    ].join('\n'),
    { encoding: 'utf8' },
  );
  console.log(`${SCRIPT}: wrote gitignored .e2e-secrets with local-only passwords (not printed).`);
}

try {
  sql(dbUrl, `UPDATE public.patria_key_settings SET recovery_wait = interval '8 seconds' WHERE singleton = 1;`);
} catch {
  console.error(`${SCRIPT}: could not shorten local recovery_wait. Is psql on PATH and Docker up?`);
  process.exit(1);
}

const users = await adminJson(url, serviceKey, 'GET', '/auth/v1/admin/users?per_page=200');
const list = users?.users ?? users ?? [];

for (const n of [1, 2, 3]) {
  const email = TEST_EMAILS[n];
  const password = passwordFor(localSecrets, n);
  const existing = list.find((row) => row.email === email);
  if (existing) {
    await adminJson(url, serviceKey, 'PUT', `/auth/v1/admin/users/${existing.id}`, {
      password,
      email_confirm: true,
    });
    sql(
      dbUrl,
      `UPDATE public.profiles SET display_name = 'Test ${n}' WHERE id = '${existing.id}';`,
    );
  } else {
    const created = await adminJson(url, serviceKey, 'POST', '/auth/v1/admin/users', {
      email,
      password,
      email_confirm: true,
    });
    const id = created?.id;
    if (id) {
      sql(
        dbUrl,
        `UPDATE public.profiles SET display_name = 'Test ${n}' WHERE id = '${id}';`,
      );
    }
  }
}

const envPath = join(APP_ROOT, '.env.e2e.local');
const anonKey = status.ANON_KEY ?? e2eEnv.EXPO_PUBLIC_SUPABASE_ANON_KEY ?? '';
writeFileSync(
  envPath,
  [
    '# Generated by e2e-setup. Local Docker only. Never put the service role key here.',
    `EXPO_PUBLIC_SUPABASE_URL=${url}`,
    `EXPO_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
    'EXPO_PUBLIC_E2E=1',
    '',
  ].join('\n'),
  { encoding: 'utf8' },
);

const emailsSql = Object.values(TEST_EMAILS)
  .map((email) => `'${email.replace(/'/g, "''")}'`)
  .join(', ');
sql(
  dbUrl,
  `SET session_replication_role = replica;
DELETE FROM public.family_spaces WHERE created_by IN (SELECT id FROM auth.users WHERE email IN (${emailsSql}));
SET session_replication_role = origin;`,
);

async function signIn(email, password) {
  const response = await fetch(`${url.replace(/\/$/, '')}/auth/v1/token?grant_type=password`, {
    method: 'POST',
    headers: {
      apikey: anonKey,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ email, password }),
  });
  const body = await response.json();
  if (!response.ok || !body.access_token || !body.user?.id) {
    throw new Error(`Could not sign in ${email} to seed through create_family_space.`);
  }
  return { accessToken: body.access_token, userId: body.user.id };
}

async function asUser(accessToken, method, path, body) {
  const response = await fetch(`${url.replace(/\/$/, '')}${path}`, {
    method,
    headers: {
      apikey: anonKey,
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
      Prefer: 'return=representation',
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await response.text();
  if (!response.ok) {
    throw new Error(`${method} ${path} failed (${response.status})`);
  }
  return text ? JSON.parse(text) : null;
}

const adminSession = await signIn(TEST_EMAILS[1], passwordFor(localSecrets, 1));
const spaceId = await asUser(adminSession.accessToken, 'POST', '/rest/v1/rpc/create_family_space', {
  p_name: E2E_FAMILY_NAME,
  p_relationship_label: 'Mom',
});
if (!spaceId) {
  throw new Error('create_family_space did not return a family id.');
}

const householdRows = await asUser(
  adminSession.accessToken,
  'GET',
  `/rest/v1/circles?family_space_id=eq.${spaceId}&kind=eq.household&select=id`,
);
const householdId = Array.isArray(householdRows) ? householdRows[0]?.id : null;
if (!householdId) {
  throw new Error('create_family_space did not create a household circle.');
}
const extendedRows = await asUser(
  adminSession.accessToken,
  'GET',
  `/rest/v1/circles?family_space_id=eq.${spaceId}&kind=eq.extended_family&select=id`,
);
const extendedId = Array.isArray(extendedRows) ? extendedRows[0]?.id : null;
if (!extendedId) {
  throw new Error('create_family_space did not create an extended family circle.');
}

async function inviteAndAccept(memberN, role, circleId = householdId) {
  const email = TEST_EMAILS[memberN];
  const created = await asUser(adminSession.accessToken, 'POST', '/rest/v1/invites', {
    family_space_id: spaceId,
    invited_by: adminSession.userId,
    email,
    role,
    default_circle_id: circleId,
  });
  const invite = Array.isArray(created) ? created[0] : created;
  const token = invite?.token;
  if (!token) {
    throw new Error(`invite insert for Test ${memberN} did not return a token.`);
  }
  const member = await signIn(email, passwordFor(localSecrets, memberN));
  await asUser(member.accessToken, 'POST', '/rest/v1/rpc/accept_invite', { p_token: token });
}

if (scenario === 'admin-elder' || scenario === 'admin-elders' || scenario === 'admin-elder-extended') {
  await inviteAndAccept(2, 'elder', householdId);
}
if (scenario === 'admin-elders') {
  await inviteAndAccept(3, 'elder', householdId);
}
if (scenario === 'admin-elder-extended') {
  await inviteAndAccept(3, 'extended_relative', extendedId);
}

// Let-in wraps cannot be seeded here: they are sealed to the phone's device
// public key after that phone opens Home. e2e.mjs does that through the app.

console.log(
  `${SCRIPT}: local users ready, recovery wait is 8 seconds, Test 1 is admin of ${E2E_FAMILY_NAME} (${scenario}), wrote .env.e2e.local (anon key only).`,
);
